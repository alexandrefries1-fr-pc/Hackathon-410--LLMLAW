// Agents re-run with the reference date (daily trigger: only the agents declared 'daily' run, the others are kept)
function runDailyAgents() {
  if (!S.data || !S.kb) return;
  if (S.data.provenance === 'llm') { rerunLlm('daily'); return; }
  if (agentEngine().backend !== 'tools') { runMistralAgents(S.data.agents?.mode === 'llm' ? 'daily' : 'upload'); return; }
  S.data.agents = runAgents(S.data, { kb: S.kb, trigger: S.data.agents ? 'daily' : 'upload', now: S.refDate, previous: S.data.agents || null });
}

// LLM mode re-run (daily trigger or 'Run the agents' button): the case agents re-run with the reference date;
// the document reader answers come from the cache, so only the case agents call Mistral again
async function rerunLlm(trigger = 'upload') {
  const eng = agentEngine();
  if (eng.backend === 'tools' || S.ui.agentsBusy) return;
  S.ui.agentsBusy = true; S.ui.agentsProgress = {};
  if (['import', 'agents'].includes(S.view)) render();
  const AG = { 'llm-read': 'READER', 'llm-chronology': 'CHRONOLOGY', 'llm-inconsistency': 'INCONSISTENCY', 'llm-documents': 'DOC', 'llm-deadlines': 'DEADLINE' };
  try {
    S.data = await analyzeWithLlm(S.data, { llm: { chat: eng.chat, model: eng.model, backend: eng.backend, concurrency: 4 }, kb: S.kb, refDate: S.refDate,
      onProgress: (p) => {
        S.ui.progress[p.step] = { ...(S.ui.progress[p.step] || {}), ...p };
        if (AG[p.step]) S.ui.agentsProgress[AG[p.step]] = p.status;
        if (['import', 'agents'].includes(S.view)) render();
      } });
    S.data.agents.trigger = trigger;
    delete S.data.llmError;
    persist();
  } catch (e) {
    if (S.data.provenance !== 'llm') S.data.llmError = String(e.message || e);
    toast(`Mistral analysis failed: ${e.message}`);
  }
  S.ui.agentsBusy = false;
  render();
}

// Where the agents run: Mistral API (cloud, default) or Ollama on this computer (local)
function agentEngine() {
  const st = S.settings || {};
  const localOk = S.llm.status?.ok && S.llm.model;
  if (st.agentsBackend !== 'local' && st.hasKey) return { backend: 'cloud', model: st.cloudModel, label: `Mistral API · ${st.cloudModel}`, chat: cloudCall };
  if (localOk) return { backend: 'local', model: S.llm.model, label: `Ollama (local) · ${S.llm.model}`, chat: ({ messages, format, numCtx, maxTokens }) => llmCall({ messages, format, numCtx, maxTokens }), note: st.agentsBackend !== 'local' ? 'Cloud mode selected but no API key: running locally.' : '' };
  return { backend: 'tools', model: null, label: 'Deterministic tools only', note: st.agentsBackend !== 'local' ? 'Cloud mode needs a Mistral API key.' : 'No local Mistral model detected.' };
}

async function cloudCall({ messages, format, maxTokens }) {
  const model = S.settings.cloudModel;
  const key = await promptKey(model, messages, format);
  const hit = S.user.llm[key] || S.demoCache[key];
  if (hit) return { ...hit, cached: true };
  const r = await api.cloud.chat({ model, messages, format, maxTokens });
  if (r.switchedFrom && S.settings.cloudModel !== r.model) {
    // the main process fell back to a model included in the Mistral plan and saved it as the new choice
    S.settings = { ...S.settings, cloudModel: r.model };
    toast(`${r.switchedFrom} is not included in your Mistral plan: using ${r.model}`);
  }
  const res = { content: r.content, ms: r.ms, model: r.model || model, at: new Date().toISOString(), backend: 'cloud' };
  S.user.llm[key] = res;
  persist();
  return res;
}

// The five agents as Mistral calls (cloud API or local Ollama), in the background after each upload and daily
async function runMistralAgents(trigger = 'upload') {
  const eng = agentEngine();
  if (!S.data || !S.kb || eng.backend === 'tools' || S.ui.agentsBusy) return;
  S.ui.agentsBusy = true; S.ui.agentsProgress = {};
  if (['import', 'agents'].includes(S.view)) render();
  try {
    const res = await runLlmAgents(S.data, {
      kb: S.kb, model: eng.model, trigger, now: S.refDate, previous: S.data.agents?.mode === 'llm' ? S.data.agents : null,
      chat: eng.chat,
      onProgress: (id, s) => { S.ui.agentsProgress[id] = s; if (['import', 'agents'].includes(S.view)) render(); },
    });
    res.backend = eng.backend;
    S.data.agents = res;
    persist();
  } catch (e) { toast(`Mistral agents: ${e.message}`); }
  S.ui.agentsBusy = false;
  if (['import', 'agents', 'synthese'].includes(S.view)) render();
}

function recomputeDeadlines() {
  const d = S.data;
  if (d.provenance === 'llm') {
    // ⚙ only the days left are recomputed; the deadlines themselves come from the Mistral deadline agent
    for (const x of d.deadlines) {
      if (!x.dueDate) continue;
      x.daysLeft = daysBetween(S.refDate, x.dueDate);
      if (x.kind !== 'CONTROLE') x.priority = x.daysLeft < 0 ? 'DEPASSEE' : x.daysLeft <= 3 ? 'CRITIQUE' : x.daysLeft <= 14 ? 'IMPORTANT' : 'SUIVI';
    }
    d.refDate = S.refDate;
    d.actions = buildActions({ deadlines: d.deadlines, missing: d.missing, contradictions: d.contradictions });
    return;
  }
  d.refDate = S.refDate;
  d.deadlines = evaluateRules(S.rules, { ...d.procedural, cameras: d.cameras, factsDate: d.factsDate }, S.refDate);
  d.actions = buildActions({ deadlines: d.deadlines, missing: d.missing, contradictions: d.contradictions });
}

