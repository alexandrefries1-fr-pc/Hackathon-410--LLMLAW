// Provenance badge: every piece of content says whether it comes from deterministic rules or from an LLM
function prov(kind, o = {}) {
  if (kind === 'llm') {
    const where = o.backend === 'cloud' ? 'cloud' : o.backend === 'local' ? 'local' : '';
    const tip = `Generated by an AI model: Mistral${o.model ? ` (${o.model})` : ''}${where === 'cloud' ? ', via the Mistral API (cloud)' : where === 'local' ? ', running on this computer' : ''}. Check it against the cited sources.`;
    return `<span class="prov llm ${where}" title="${esc(tip)}">✦ Mistral${where ? ` · ${where}` : ''}</span>`;
  }
  return `<span class="prov rules" title="${esc(o.tip || 'Produced by deterministic rules, without AI: the same documents always give the same result.')}">⚙ Rules</span>`;
}

